import assert from 'node:assert/strict';
import test from 'node:test';
import { openDb } from '../src/db.js';
import { readProofArgument } from '../src/argument.js';

test('the stored argument reads back for the side panel, and bad rows degrade instead of throwing', (t) => {
  const db = openDb(':memory:');
  t.after(() => db.close());
  const columns = (db.prepare('PRAGMA table_info(audit_runs)').all() as Array<{ name: string }>).map((c) => c.name);
  assert.ok(columns.includes('proverOptionsJson'));

  db.exec(`
    INSERT INTO projects VALUES ('p', 'overleaf', NULL, NULL, 'Test', 'now', 'now', '{}');
    INSERT INTO audit_runs (auditRunId, projectId, requestId, mode, proverOptionsJson, status, startedAt)
      VALUES ('r', 'p', 'q', 'proofSkeleton', '{"model":"anthropic/claude-fable-5.2","budget":"hard"}', 'finished', 'now');
  `);
  assert.equal(readProofArgument(db, 'r'), null, 'no steps, no argument');

  const insertStep = db.prepare('INSERT INTO proof_steps (proofStepId, auditRunId, idx, sourceText, status, artifactsJson) VALUES (?, ?, ?, ?, ?, ?)');
  insertStep.run('s1', 'r', 1, 'By [X], ...', 'checked', JSON.stringify({
    claim: 'D is generated by one piece', uses: [], cites: [{ idx: 1, name: 'Bergman', status: 'assumed' }],
    leanSource: 'theorem step1 : laleCite1 → P := by sorry', backtranslation: 'If Bergman, then P.',
    diagnostics: [], proof: { status: 'proved', closedBy: 'agent', diagnostics: [], spentUsd: 3.5, turns: 41 },
  }));
  insertStep.run('s2', 'r', 2, 'Hence ...', 'checked', JSON.stringify({
    claim: 'the growth is linear', uses: [1], cites: [],
    proof: { status: 'unproved', closedBy: null, diagnostics: ['Agent stopped (gaveUp)'], report: 'needs a bound on dim(SU) that does not follow' },
  }));
  insertStep.run('s3', 'r', 3, 'garbage', 'blocked', '{not json');
  db.prepare('INSERT INTO proof_arguments (auditRunId, citationsJson, compositionJson, agentSpendUsd, createdAt) VALUES (?, ?, ?, ?, ?)').run(
    'r',
    JSON.stringify([
      { idx: 1, name: 'Bergman', statement: 'no GK dim in (1,2)', status: 'assumed', reason: 'not proved here', leanSource: 'def laleCite1 : Prop := Q', backtranslation: 'Q' },
      { idx: 2, bogus: true },
    ]),
    JSON.stringify({ status: 'skipped', conditionalOn: [], closedBy: null, report: null, diagnostics: [], proverModel: 'anthropic/claude-fable-5.2', budget: 'hard' }),
    7.25,
    'now',
  );

  const argument = readProofArgument(db, 'r')!;
  assert.equal(argument.steps.length, 3);
  assert.deepEqual(argument.steps[0]!.cites, [1]);
  assert.equal(argument.steps[0]!.closedBy, 'agent');
  assert.equal(argument.steps[0]!.turns, 41);
  assert.equal(argument.steps[1]!.report, 'needs a bound on dim(SU) that does not follow');
  assert.deepEqual(argument.steps[1]!.uses, [1]);
  assert.equal(argument.steps[2]!.proofStatus, 'skipped', 'unreadable artifacts degrade');
  assert.equal(argument.steps[2]!.claim, 'garbage');
  assert.equal(argument.citations.length, 1, 'malformed citation dropped');
  assert.equal(argument.composition?.status, 'skipped');
  assert.equal(argument.agentSpendUsd, 7.25);
  assert.equal(argument.proverModel, 'anthropic/claude-fable-5.2');
  assert.equal(argument.budget, 'hard');
});
